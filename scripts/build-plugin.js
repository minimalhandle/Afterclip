// Generates the Stream Deck plugin's manifest actions and static images. Keys draw their live image at runtime.
const fs = require('node:fs');
const path = require('node:path');
const { tilePng, markPng, ringForKey, WHITE } = require('./build-brand');

const plugin = path.join(__dirname, '..', 'streamdeck', 'com.afterclip.clips.sdPlugin');
const imgs = path.join(plugin, 'imgs');
fs.rmSync(imgs, { recursive: true, force: true });
fs.mkdirSync(imgs, { recursive: true });
fs.writeFileSync(path.join(plugin, 'ring.cjs'), `// Generated by scripts/build-brand.js from the logo's shapes.\nmodule.exports = ${JSON.stringify(ringForKey())};\n`);
const { keySvg, listIcon } = require(path.join(plugin, 'key-art.cjs'));

// Every fixed length gets its own action, generated here so icons and the manifest can't disagree.
// The plugin reads the length back out of the action's UUID, such as save-15-sec.
const LENGTHS = [[15, 'sec'], [30, 'sec'], [1, 'min'], [2, 'min'], [3, 'min'], [5, 'min'], [10, 'min'], [15, 'min'], [20, 'min'], [30, 'min']];
const action = (name, title, tooltip, extra = {}) => ({
  UUID: `com.afterclip.clips.${name}`,
  Name: title,
  Tooltip: tooltip,
  Icon: `imgs/action-${name}`,
  Controllers: ['Keypad'],
  DisableAutomaticStates: true,
  SupportedInMultiActions: true,
  UserTitleEnabled: false,
  States: [{ Image: `imgs/${name}`, ShowTitle: false }],
  ...extra,
});
// Stream Deck + dials, which draw on the touch strip above them.
const dial = (name, title, tooltip, triggers) => action(name, title, tooltip, {
  Controllers: ['Encoder'],
  Encoder: { layout: '$B1', TriggerDescription: triggers },
  SupportedInMultiActions: false,
});
const manifestFile = path.join(plugin, 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
manifest.Version = '0.10.0.0';
// Every key's settings show the address it connects to, so a Stream Deck can control Afterclip on another PC.
manifest.PropertyInspectorPath = 'ui/connection.html';
manifest.Actions = [
  ...LENGTHS.map(([n, unit]) => action(`save-${n}-${unit}`, `Save Last ${n} ${unit === 'sec' ? 'Sec' : 'Min'}`, `Save the last ${n} ${unit === 'sec' ? 'seconds' : n === 1 ? 'minute' : 'minutes'} of your buffer.`)),
  action('save-full', 'Save Full Buffer', 'Save everything in your buffer.'),
  action('record', 'Record', 'Start or stop a full recording. The key shows the live state.'),
  action('mic', 'Mute Mic In Clips', 'Mute your mic in recordings and clips. It only affects Afterclip, not your calls.'),
  action('clean-mic', 'Clean Mic', 'Turn noise suppression and the noise gate on or off for your mic in clips.'),
  action('marker', 'Add Marker', 'Mark this moment in the running recording.'),
  action('clip', 'Save Custom Length', "Save a length you choose in the key's settings.", { PropertyInspectorPath: 'ui/clip.html' }),
  action('open-panel', 'Open Afterclip', "Open Afterclip's panel."),
  action('open-clips', 'Open Clips Folder', 'Open the folder your clips are saved in.'),
  action('edit-last', 'Edit Last Clip', 'Open your newest clip in the editor.'),
  action('copy-last', 'Copy Last Clip', 'Copy your newest clip, ready to paste into a chat or another app.'),
  action('screenshot', 'Take Screenshot', 'Save a picture of what Afterclip is capturing.'),
  action('compress-last', 'Compress Last Clip', 'Make a smaller copy of your newest clip, ready to share.'),
  action('discord-last', 'Send Last Clip to Discord', 'Send your newest clip to the Discord channel set in Afterclip.'),
  action('vertical-last', 'Vertical Copy of Last Clip', 'Make a 9:16 copy of your newest clip for phones, with your webcam on top if it has one.'),
  action('star-last', 'Star Last Clip', 'Add your newest clip to your favourites, so clean-up never removes it. Press again to take the star off.'),
  action('webcam', 'Show Your Webcam', 'Turn your webcam in clips on or off, without restarting capture. Choose the webcam in Afterclip first.'),
  action('talk', 'Hold to Talk', 'Hold to put your mic in clips, with Push to talk turned on in Afterclip.', { SupportedInMultiActions: false }),
  dial('mic-dial', 'Mic Volume', 'Turn to change your mic volume in clips. Press to mute your mic in clips.', { Rotate: 'Mic volume', Push: 'Mute mic in clips', Touch: 'Mute mic in clips' }),
  dial('clip-dial', 'Clip Length Dial', 'Turn to choose a length, then press to save a clip. The bar shows how full your buffer is.', { Rotate: 'Choose a length', Push: 'Save a clip', Touch: 'Save a clip' }),
];
fs.writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);

fs.writeFileSync(path.join(imgs, 'plugin.png'), tilePng(288));
fs.writeFileSync(path.join(imgs, 'plugin@2x.png'), tilePng(576));
fs.writeFileSync(path.join(imgs, 'category.png'), markPng(28, WHITE));
fs.writeFileSync(path.join(imgs, 'category@2x.png'), markPng(56, WHITE));
for (const [name, list, face] of [
  ...LENGTHS.map(([n, unit]) => [`save-${n}-${unit}`, String(n), { big: String(n), small: unit.toUpperCase() }]),
  ['save-full', 'F', { big: 'FULL', small: 'BUFFER' }],
  ['record', 'R', { symbol: 'record', small: 'REC' }],
  ['mic', 'M', { symbol: 'mic', small: 'MIC ON' }],
  ['clean-mic', 'N', { symbol: 'clean', small: 'CLEAN MIC' }],
  ['marker', 'K', { symbol: 'marker', small: 'MARKER' }],
  ['clip', 'C', { big: '30', small: 'SEC' }],
  ['open-panel', 'O', { symbol: 'panel', small: 'OPEN' }],
  ['open-clips', 'L', { symbol: 'folder', small: 'CLIPS' }],
  ['edit-last', 'E', { symbol: 'edit', small: 'EDIT LAST' }],
  ['copy-last', 'P', { symbol: 'copy', small: 'COPY LAST' }],
  ['screenshot', 'S', { symbol: 'camera', small: 'SHOT' }],
  ['compress-last', 'Z', { symbol: 'compress', small: 'COMPRESS' }],
  ['discord-last', 'D', { symbol: 'send', small: 'DISCORD' }],
  ['vertical-last', 'Y', { symbol: 'vertical', small: 'VERTICAL' }],
  ['star-last', 'A', { symbol: 'star', small: 'STAR LAST' }],
  ['webcam', 'W', { symbol: 'webcamOff', small: 'CAM OFF' }],
  ['talk', 'H', { symbol: 'mic', small: 'HOLD' }],

  ['mic-dial', 'V', { symbol: 'mic', small: 'VOLUME' }],
  ['clip-dial', 'T', { big: '30', small: 'SEC' }],
]) {

  fs.writeFileSync(path.join(imgs, `action-${name}.svg`), listIcon(list));
  fs.writeFileSync(path.join(imgs, `${name}.svg`), keySvg(face));
}
